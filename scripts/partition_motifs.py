#!/usr/bin/env python3
"""
Partition JASPAR motifs into selection, discovery and confirmation sets.

Similarity groups are taken from the official JASPAR 2026 CORE Plants
matrix-clustering archive. This script does not calculate motif similarity.

Every official JASPAR cluster is assigned wholly to one partition so that
closely related motifs cannot occur in both layer selection and later
evaluation.

The deterministic largest-first allocator uses the recorded seed and aims
for three equally sized motif partitions.

Inputs:
    1. JASPAR 2026 CORE Plants non-redundant MEME file.
    2. jaspar_official_clusters.tsv generated by
       extract_jaspar_clusters.py.

Outputs:
    motif_partition.tsv
    motifs_selection.meme
    motifs_discovery.meme
    motifs_confirmation.meme
"""

import argparse
import csv
import os
import re
from collections import defaultdict

import numpy as np


SEED = 20260829

EXPECTED_MOTIFS = 927
EXPECTED_CLUSTERS = 55

TARGETS = {
    "selection": 1 / 3,
    "discovery": 1 / 3,
    "confirmation": 1 / 3,
}

MATRIX_ID_PATTERN = re.compile(r"^MA\d+\.\d+$")
CLUSTER_PATTERN = re.compile(r"^cluster_\d{2}$")


def read_meme(path):
    """Read motifs while preserving their original MEME text."""

    with open(path, "r", encoding="utf-8-sig") as file:
        text = file.read()

    alphabet_match = re.search(
        r"ALPHABET\s*=\s*(\S+)",
        text,
    )

    if (
        alphabet_match
        and alphabet_match.group(1).upper() != "ACGT"
    ):
        raise SystemExit(
            f"unexpected MEME alphabet: "
            f"{alphabet_match.group(1)}"
        )

    first_motif = re.search(r"(?m)^MOTIF\s+", text)

    if first_motif is None:
        raise SystemExit(
            f"no motifs were found in MEME file: {path}"
        )

    header = text[:first_motif.start()]
    motifs = []
    observed_ids = set()

    blocks = re.split(r"(?m)^MOTIF\s+", text)[1:]

    for block in blocks:
        lines = block.strip().splitlines()

        if not lines:
            continue

        parts = lines[0].split(maxsplit=1)
        motif_id = parts[0]
        motif_name = (
            parts[1].strip()
            if len(parts) > 1
            else motif_id
        )

        if not MATRIX_ID_PATTERN.fullmatch(motif_id):
            raise SystemExit(
                f"unexpected JASPAR Matrix ID: {motif_id}"
            )

        if motif_id in observed_ids:
            raise SystemExit(
                f"duplicated Matrix ID in MEME file: {motif_id}"
            )

        observed_ids.add(motif_id)

        rows = []
        reading_matrix = False

        for line in lines[1:]:
            if line.startswith("letter-probability matrix"):
                reading_matrix = True
                continue

            if not reading_matrix:
                continue

            values = line.split()

            if len(values) == 4:
                try:
                    rows.append(
                        [float(value) for value in values]
                    )
                    continue
                except ValueError:
                    pass

            if rows:
                break

        if not rows:
            raise SystemExit(
                f"could not parse matrix for {motif_id}"
            )

        raw_text = "MOTIF " + block.rstrip() + "\n"

        motifs.append(
            {
                "motif_id": motif_id,
                "name": motif_name,
                "length": len(rows),
                "raw_text": raw_text,
            }
        )

    return header, motifs


def read_official_clusters(path):
    """Read and validate jaspar_official_clusters.tsv."""

    required_columns = {
        "matrix_id",
        "motif_name",
        "jaspar_cluster",
        "cluster_size",
    }

    records = {}
    clusters = defaultdict(list)
    declared_sizes = defaultdict(set)

    with open(
        path,
        "r",
        encoding="utf-8-sig",
        newline="",
    ) as file:
        reader = csv.DictReader(
            file,
            delimiter="\t",
        )

        actual_columns = set(reader.fieldnames or [])
        missing_columns = required_columns - actual_columns

        if missing_columns:
            raise SystemExit(
                "cluster mapping is missing columns: "
                + ", ".join(sorted(missing_columns))
            )

        for line_number, row in enumerate(
            reader,
            start=2,
        ):
            matrix_id = row["matrix_id"].strip()
            motif_name = row["motif_name"].strip()
            cluster = row["jaspar_cluster"].strip()

            if not MATRIX_ID_PATTERN.fullmatch(matrix_id):
                raise SystemExit(
                    f"invalid Matrix ID at line "
                    f"{line_number}: {matrix_id!r}"
                )

            if not CLUSTER_PATTERN.fullmatch(cluster):
                raise SystemExit(
                    f"invalid cluster at line "
                    f"{line_number}: {cluster!r}"
                )

            try:
                declared_size = int(
                    row["cluster_size"]
                )
            except ValueError as error:
                raise SystemExit(
                    f"invalid cluster size at line "
                    f"{line_number}"
                ) from error

            if matrix_id in records:
                raise SystemExit(
                    "duplicated Matrix ID in cluster "
                    f"mapping: {matrix_id}"
                )

            records[matrix_id] = {
                "name": motif_name,
                "cluster": cluster,
                "declared_size": declared_size,
            }

            clusters[cluster].append(matrix_id)
            declared_sizes[cluster].add(
                declared_size
            )

    if len(records) != EXPECTED_MOTIFS:
        raise SystemExit(
            f"expected {EXPECTED_MOTIFS} cluster-map rows, "
            f"found {len(records)}"
        )

    if len(clusters) != EXPECTED_CLUSTERS:
        raise SystemExit(
            f"expected {EXPECTED_CLUSTERS} official "
            f"clusters, found {len(clusters)}"
        )

    for cluster, motif_ids in clusters.items():
        sizes = declared_sizes[cluster]

        if len(sizes) != 1:
            raise SystemExit(
                f"{cluster} has inconsistent declared sizes: "
                f"{sorted(sizes)}"
            )

        declared_size = next(iter(sizes))
        actual_size = len(motif_ids)

        if declared_size != actual_size:
            raise SystemExit(
                f"{cluster}: declared size "
                f"{declared_size}, actual size "
                f"{actual_size}"
            )

    return records, dict(clusters)


def cross_validate_inputs(motifs, cluster_records):
    """Require an exact ID and name match between both inputs."""

    meme_by_id = {
        motif["motif_id"]: motif
        for motif in motifs
    }

    meme_ids = set(meme_by_id)
    cluster_ids = set(cluster_records)

    missing_from_clusters = meme_ids - cluster_ids
    extra_in_clusters = cluster_ids - meme_ids

    if missing_from_clusters or extra_in_clusters:
        raise SystemExit(
            "MEME and official cluster mapping contain "
            "different Matrix IDs. "
            f"Missing from mapping: "
            f"{sorted(missing_from_clusters)[:10]}; "
            f"extra in mapping: "
            f"{sorted(extra_in_clusters)[:10]}"
        )

    name_mismatches = []

    for matrix_id in sorted(meme_ids):
        meme_name = meme_by_id[matrix_id]["name"]
        cluster_name = cluster_records[matrix_id]["name"]

        if meme_name != cluster_name:
            name_mismatches.append(
                (
                    matrix_id,
                    meme_name,
                    cluster_name,
                )
            )

    if name_mismatches:
        examples = "; ".join(
            f"{matrix_id}: MEME={meme_name!r}, "
            f"mapping={cluster_name!r}"
            for matrix_id, meme_name, cluster_name
            in name_mismatches[:10]
        )

        raise SystemExit(
            f"found {len(name_mismatches)} motif-name "
            f"mismatch(es): {examples}"
        )


def allocate_clusters(clusters):
    """Assign whole official clusters to three partitions."""

    total_motifs = sum(
        len(motif_ids)
        for motif_ids in clusters.values()
    )

    if total_motifs != EXPECTED_MOTIFS:
        raise SystemExit(
            f"expected {EXPECTED_MOTIFS} motifs, "
            f"found {total_motifs}"
        )

    rng = np.random.default_rng(SEED)

    # Generate tie-break values in cluster-name order so that
    # TSV row order cannot change the resulting allocation.
    tie_break = {
        cluster: float(rng.random())
        for cluster in sorted(clusters)
    }

    order = sorted(
        clusters,
        key=lambda cluster: (
            -len(clusters[cluster]),
            tie_break[cluster],
        ),
    )

    goal = {
        partition: fraction * total_motifs
        for partition, fraction in TARGETS.items()
    }

    filled = {
        partition: 0
        for partition in TARGETS
    }

    partition_clusters = {
        partition: []
        for partition in TARGETS
    }

    cluster_assignment = {}

    for cluster in order:
        deficits = {
            partition: goal[partition] - filled[partition]
            for partition in TARGETS
        }

        largest_deficit = max(deficits.values())

        tied_partitions = [
            partition
            for partition in TARGETS
            if deficits[partition]
            >= largest_deficit - 1e-9
        ]

        selected_partition = tied_partitions[
            int(rng.integers(len(tied_partitions)))
        ]

        cluster_assignment[cluster] = selected_partition

        cluster_size = len(clusters[cluster])

        filled[selected_partition] += cluster_size

        partition_clusters[selected_partition].append(
            cluster
        )

    expected_per_partition = (
        total_motifs // len(TARGETS)
    )

    for partition in TARGETS:
        if filled[partition] != expected_per_partition:
            raise SystemExit(
                f"{partition} received "
                f"{filled[partition]} motifs; expected "
                f"{expected_per_partition}"
            )

    largest_three = sorted(
        clusters,
        key=lambda cluster: (
            -len(clusters[cluster]),
            cluster,
        ),
    )[:3]

    largest_three_partitions = {
        cluster_assignment[cluster]
        for cluster in largest_three
    }

    if len(largest_three_partitions) != 3:
        raise SystemExit(
            "the three largest official clusters were not "
            "distributed across three different partitions"
        )

    return (
        cluster_assignment,
        partition_clusters,
        filled,
    )


def write_outputs(
    outdir,
    header,
    motifs,
    cluster_records,
    clusters,
    cluster_assignment,
):
    """Write the partition table and three MEME files."""

    os.makedirs(outdir, exist_ok=True)

    partition_path = os.path.join(
        outdir,
        "motif_partition.tsv",
    )

    with open(
        partition_path,
        "w",
        encoding="utf-8",
        newline="",
    ) as file:
        file.write(
            "motif_id\tname\tlength\tgroup\tpartition\n"
        )

        for motif in motifs:
            motif_id = motif["motif_id"]
            cluster = cluster_records[motif_id]["cluster"]
            partition = cluster_assignment[cluster]

            file.write(
                f"{motif_id}\t"
                f"{motif['name']}\t"
                f"{motif['length']}\t"
                f"{cluster}\t"
                f"{partition}\n"
            )

    for partition in TARGETS:
        output_path = os.path.join(
            outdir,
            f"motifs_{partition}.meme",
        )

        with open(
            output_path,
            "w",
            encoding="utf-8",
            newline="",
        ) as file:
            file.write(header)

            for motif in motifs:
                motif_id = motif["motif_id"]
                cluster = cluster_records[
                    motif_id
                ]["cluster"]

                if (
                    cluster_assignment[cluster]
                    == partition
                ):
                    file.write(
                        motif["raw_text"] + "\n"
                    )


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Partition JASPAR 2026 CORE Plants motifs "
            "using official JASPAR similarity clusters."
        )
    )

    parser.add_argument(
        "--meme",
        required=True,
        help=(
            "JASPAR 2026 CORE Plants "
            "non-redundant MEME file."
        ),
    )

    parser.add_argument(
        "--clusters",
        required=True,
        help=(
            "Official motif-to-cluster TSV generated by "
            "extract_jaspar_clusters.py."
        ),
    )

    parser.add_argument(
        "--outdir",
        default="data/motifs",
    )

    # Reject old commands explicitly instead of silently
    # pretending that a threshold is still used.
    parser.add_argument(
        "--threshold",
        type=float,
        default=None,
        help=argparse.SUPPRESS,
    )

    args = parser.parse_args()

    if args.threshold is not None:
        raise SystemExit(
            "--threshold is no longer supported. "
            "Motif groups now come from the official "
            "JASPAR clustering archive."
        )

    header, motifs = read_meme(args.meme)

    cluster_records, clusters = read_official_clusters(
        args.clusters
    )

    cross_validate_inputs(
        motifs,
        cluster_records,
    )

    (
        cluster_assignment,
        partition_clusters,
        filled,
    ) = allocate_clusters(clusters)

    print(
        f"{len(motifs)} motifs read from "
        f"{args.meme}"
    )

    print(
        f"{len(clusters)} official JASPAR clusters "
        f"read from {args.clusters}"
    )

    print(
        "\nPer-partition composition:"
    )

    for partition in TARGETS:
        assigned_clusters = partition_clusters[
            partition
        ]

        sizes = sorted(
            (
                len(clusters[cluster])
                for cluster in assigned_clusters
            ),
            reverse=True,
        )

        largest_size = sizes[0]
        largest_share = (
            largest_size / filled[partition]
        )

        print(
            f"  {partition:<13} "
            f"{filled[partition]:>4} motifs in "
            f"{len(assigned_clusters):>2} clusters; "
            f"largest cluster {largest_size} "
            f"({100 * largest_share:.0f}% of set)"
        )

        if largest_share > 0.25:
            print(
                f"  NOTE: cluster-balanced scoring "
                f"should be used because one cluster "
                f"contains more than 25% of the "
                f"{partition} motifs"
            )

    write_outputs(
        outdir=args.outdir,
        header=header,
        motifs=motifs,
        cluster_records=cluster_records,
        clusters=clusters,
        cluster_assignment=cluster_assignment,
    )

    print(
        f"\nwrote {args.outdir}/motif_partition.tsv "
        "and three .meme files"
    )


if __name__ == "__main__":
    main()